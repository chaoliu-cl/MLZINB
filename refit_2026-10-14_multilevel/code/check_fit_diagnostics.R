suppressPackageStartupMessages(library(glmmTMB))
set.seed(20261014)
d <- data.frame(y=rnbinom(400,mu=2,size=.7),x=rnorm(400),g=factor(rep(1:20,each=20)))
m <- glmmTMB(y~x+(1|g),ziformula=~x,data=d,family=nbinom2())
cat("Optimizer\n")
print(m$fit$convergence)
print(m$sdr$pdHess)
cat("Gradient\n")
g <- m$obj$gr(m$fit$par)
print(g)
cat("Covariance dimensions\n")
print(dim(m$sdr$cov.fixed))
cat("Newton step in standard error units\n")
print(max(abs(m$sdr$cov.fixed %*% g)/sqrt(diag(m$sdr$cov.fixed))))
cat("Fixed coefficients\n")
print(summary(m)$coefficients)
